export const mvuEvents = Object.freeze({
    VARIABLE_INITIALIZED: 'mag_variable_initialized',
    VARIABLE_UPDATE_STARTED: 'mag_variable_update_started',
    COMMAND_PARSED: 'mag_command_parsed',
    VARIABLE_UPDATE_ENDED: 'mag_variable_update_ended',
    BEFORE_MESSAGE_UPDATE: 'mag_before_message_update',
    SINGLE_VARIABLE_UPDATED: 'mag_variable_updated',
});
const mvuAliases = Object.fromEntries(Object.entries(mvuEvents).map(([key, value]) => [`mvu:${key.toLowerCase()}`, value]));
export function canonicalEvent(name: string): string {
    return name === 'chat_changed' ? tavernEvents.CHAT_CHANGED
        : name === 'generation_after_commands' ? tavernEvents.GENERATION_AFTER_COMMANDS
        : name === 'mag_variable_initiailized' ? mvuEvents.VARIABLE_INITIALIZED : mvuAliases[name] ?? name;
}
